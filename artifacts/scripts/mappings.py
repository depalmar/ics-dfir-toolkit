#!/usr/bin/env python3
"""Generate MAPPINGS.md: ATT&CK coverage across the knowledge base.

  python artifacts/scripts/mappings.py          # write MAPPINGS.md
  python artifacts/scripts/mappings.py --check  # CI: fail if MAPPINGS.md is stale

For every ATT&CK technique any record names, one row says who uses it
(malware, actors, incidents), what can see it (data sources) and what looks
for it (hunts, packs, rules). A technique an adversary is recorded using with
nothing hunting or detecting it is listed as a gap. Hand-maintained mapping
tables drift; this one cannot, because CI regenerates it and compares.

ICS-matrix technique ids are T08xx; the rest are Enterprise. Technique names
are not stored in the repository, so ids link to attack.mitre.org.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "MAPPINGS.md"
ART = ROOT / "artifacts"
ATT = re.compile(r"^T\d{4}(\.\d{3})?$")
SIGMA_ATT = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$")
ROLES = ("used", "seen", "hunted", "detected")


def load(sub: str) -> list[dict]:
    return [yaml.safe_load(p.read_text()) for p in sorted((ART / sub).glob("*.yml"))]


def link(t: str) -> str:
    return f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)"


def matrix(t: str) -> str:
    return "ICS" if t.startswith("T08") else "Enterprise"


def ids(vals) -> list[str]:
    return [v for v in vals or [] if isinstance(v, str) and ATT.match(v)]


def coverage() -> dict[str, dict[str, set[str]]]:
    cov: dict[str, dict[str, set[str]]] = {}

    def add(techs, role: str, who: str) -> None:
        for t in ids(techs):
            cov.setdefault(t, {r: set() for r in ROLES})[role].add(who)

    for m in load("intel/malware"):
        add(m.get("attack"), "used", m["id"])
        for c in m.get("capabilities") or []:
            add(c.get("attack"), "used", m["id"])
    for a in load("intel/actors"):
        add(a.get("attack"), "used", a["id"])
    for i in load("intel/incidents"):
        for step in i.get("chain") or []:
            add(step.get("attack"), "used", i["id"])
    for d in load("visibility"):
        for e in d.get("events") or []:
            add(e.get("attack"), "seen", d["id"])
    for h in load("hunts"):
        add(h.get("attack"), "hunted", h["id"])
    for p in load("packs"):
        for det in p.get("detect") or []:
            add(det.get("attack"), "detected", p["id"])
    for f in sorted(ROOT.glob("[0-9][0-9]-*/*.yml")):
        tags = (yaml.safe_load(f.read_text()) or {}).get("tags") or []
        techs = [m.group(1).upper() for t in tags if (m := SIGMA_ATT.match(str(t)))]
        add(techs, "detected", f.relative_to(ROOT).as_posix())
    return cov


def cell(s: set[str]) -> str:
    return ", ".join(sorted(s)) or "-"


def build() -> str:
    cov = coverage()
    techs = sorted(cov, key=lambda t: (matrix(t) != "ICS", t))
    gaps = [t for t in techs if cov[t]["used"] and not (cov[t]["hunted"] or cov[t]["detected"])]
    unseen = [t for t in techs if cov[t]["used"] and not cov[t]["seen"]]
    n_ics = sum(matrix(t) == "ICS" for t in techs)
    L = ["# Mappings", "",
         "Generated by `artifacts/scripts/mappings.py`. Do not edit by hand.", "",
         f"{len(techs)} ATT&CK techniques are named across the knowledge base ({n_ics} ICS, "
         f"{len(techs) - n_ics} Enterprise). **Used** = malware, actors or incidents recorded using it; "
         "**seen** = data sources whose events show it; **hunted** = hunts; **detected** = packs and Sigma rules.",
         "",
         f"## Gaps: used, but nothing hunts or detects it ({len(gaps)})", ""]
    if gaps:
        L += ["| Technique | Matrix | Used by | Seen by |", "|---|---|---|---|"]
        L += [f"| {link(t)} | {matrix(t)} | {cell(cov[t]['used'])} | {cell(cov[t]['seen'])} |" for t in gaps]
    else:
        L.append("None.")
    L += ["", f"## Blind spots: used, but no data source records it ({len(unseen)})", ""]
    L += [f"- {link(t)} ({matrix(t)}): used by {cell(cov[t]['used'])}" for t in unseen] or ["None."]
    L += ["", "## Coverage by technique", "",
          "| Technique | Matrix | Used by | Seen by | Hunted by | Detected by |", "|---|---|---|---|---|---|"]
    L += [f"| {link(t)} | {matrix(t)} | {cell(cov[t]['used'])} | {cell(cov[t]['seen'])} | "
          f"{cell(cov[t]['hunted'])} | {cell(cov[t]['detected'])} |" for t in techs]
    L += ["", "## Detection packs", "",
          "| Pack | Detection | Type | Tier | Evidence class | ATT&CK | Rules |", "|---|---|---|---|---|---|---|"]
    for p in load("packs"):
        for d in p.get("detect") or []:
            L.append(f"| {p['id']} | `{d['id']}` | {d['type']} | {d['tier']} | {d['evidence_class']} | "
                     f"{', '.join(d.get('attack') or []) or '-'} | {', '.join(f'`{r}`' for r in d.get('rules') or []) or '-'} |")
    L += ["", "## Rules", "", "| File | Format | ATT&CK / sids |", "|---|---|---|"]
    for f in sorted(list(ROOT.glob("[0-9][0-9]-*/*.yml")) + list(ROOT.glob("[0-9][0-9]-*/*.yar"))
                    + list(ROOT.glob("[0-9][0-9]-*/*.rules"))):
        rel = f.relative_to(ROOT).as_posix()
        text = f.read_text()
        if f.suffix == ".yml":
            tags = (yaml.safe_load(text) or {}).get("tags") or []
            att = sorted({m.group(1).upper() for t in tags if (m := SIGMA_ATT.match(str(t)))})
            L.append(f"| `{rel}` | Sigma | {', '.join(att) or '-'} |")
        elif f.suffix == ".rules":
            sids = sorted(set(re.findall(r"\bsid:\s*(\d+)", text)), key=int)
            L.append(f"| `{rel}` | Suricata | sid {', '.join(sids) or '-'} |")
        else:
            L.append(f"| `{rel}` | YARA | - |")
    return "\n".join(L) + "\n"


def main() -> int:
    content = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            print("MAPPINGS.md is stale: run python artifacts/scripts/mappings.py")
            return 1
        print("MAPPINGS.md is current")
        return 0
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
